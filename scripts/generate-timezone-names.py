"""Generate Chinese display names for IANA time zones as a frontend TS module.

Run from the repo root:  backend/.venv/Scripts/python.exe scripts/generate-timezone-names.py
Requires babel (pip install babel). Output: frontend/src/timezone-names.ts
"""
from pathlib import Path

from babel.dates import get_timezone_location, get_timezone_name
from zoneinfo import ZoneInfo, ZoneInfoNotFoundError, available_timezones

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / 'frontend' / 'src' / 'timezone-names.ts'


def chinese_name(zone_id):
    tz = ZoneInfo(zone_id)
    for fetch in (get_timezone_name, get_timezone_location):
        try:
            name = fetch(tz, locale='zh_CN')
        except KeyError:
            continue
        if name and name != zone_id and not name.isascii():
            return name
    return None


def chinese_location(zone_id):
    try:
        name = get_timezone_location(ZoneInfo(zone_id), locale='zh_CN')
    except (KeyError, ZoneInfoNotFoundError, ValueError):
        return None
    return name if name and not name.isascii() else None


def main():
    zones = sorted(available_timezones())
    rows = []
    for zone in sorted(set(zones)):
        if zone.startswith(('Etc/', 'SystemV/', 'US/', 'posix/')):
            continue
        try:
            name = chinese_name(zone)
        except (ZoneInfoNotFoundError, ValueError, KeyError):
            continue
        if name:
            try:
                location = chinese_location(zone)
            except (ZoneInfoNotFoundError, ValueError, KeyError):
                location = None
            rows.append((zone, name, location if location and location != name else None))
    entries = ',\n'.join(f"  {zone!r}: {name!r}" for zone, name, _ in rows)
    aliases = ',\n'.join(f"  {zone!r}: {location!r}" for zone, _, location in rows if location)
    body = (
        '// Generated by scripts/generate-timezone-names.py (babel/CLDR zh_CN); do not edit by hand.\n'
        f'export const timezoneNames: Record<string, string> = {{\n{entries},\n}};\n\n'
        '// Extra Chinese city/location names kept only for search (e.g. 上海 -> Asia/Shanghai).\n'
        f'export const timezoneSearchAliases: Record<string, string> = {{\n{aliases},\n}};\n')
    OUTPUT.write_text(body, encoding='utf-8')
    print(f'wrote {len(rows)} zone names ({sum(1 for _, _, a in rows if a)} aliases) to {OUTPUT}')


if __name__ == '__main__':
    main()
