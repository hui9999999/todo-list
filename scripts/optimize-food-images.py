"""Build versioned WebP delivery assets while preserving the source images.

Sources are WebP q90 masters (converted from the original PNGs to keep the
repository small); 960/480px delivery copies are regenerated from them."""
from concurrent.futures import ThreadPoolExecutor
import hashlib
import json
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'frontend' / 'public' / 'food'
OUTPUT = SOURCE / 'optimized'
OUTPUT.mkdir(exist_ok=True)
RECIPE = b'webp-v1:960:480:quality80:method6'


def optimize(path):
    digest = hashlib.sha256(RECIPE + path.read_bytes()).hexdigest()[:12]
    urls = {}
    with Image.open(path) as original:
        for field, side, suffix in [('image', 960, ''), ('thumbnail', 480, '-small')]:
            name = f'{path.stem}.{digest}{suffix}.webp'
            target = OUTPUT / name
            if not target.exists():
                image = original.convert('RGB')
                image.thumbnail((side, side), Image.Resampling.LANCZOS)
                image.save(target, 'WEBP', quality=80, method=6)
            urls[field] = '/food/optimized/' + name
    return path.stem, urls, path.stat().st_size


sources = sorted([*SOURCE.glob('*.png'), *SOURCE.glob('*.webp')])
with ThreadPoolExecutor(max_workers=4) as pool:
    results = list(pool.map(optimize, sources))
manifest = {name: urls for name, urls, _ in results}
# Drop delivery files that no longer match any source (e.g. after re-encoding masters).
referenced = {Path(urls['image']).name for urls in manifest.values()} | {Path(urls['thumbnail']).name for urls in manifest.values()}
for stale in OUTPUT.glob('*.webp'):
    if stale.name not in referenced:
        stale.unlink()
generated = ROOT / 'frontend' / 'src' / 'food-image-assets.ts'
generated.write_text(
    '// Generated by scripts/optimize-food-images.py; keep the original source files.\n'
    'export const foodImageAssets: Record<string, {image: string; thumbnail: string}> = '
    + json.dumps(manifest, ensure_ascii=False, indent=2) + ';\n', encoding='utf-8')
source_bytes = sum(size for _, _, size in results)
full_bytes = sum((OUTPUT / Path(urls['image']).name).stat().st_size for urls in manifest.values())
thumbnail_bytes = sum((OUTPUT / Path(urls['thumbnail']).name).stat().st_size for urls in manifest.values())
print(json.dumps({'images': len(results), 'source_bytes': source_bytes,
                  'full_bytes': full_bytes, 'thumbnail_bytes': thumbnail_bytes,
                  'full_reduction_percent': round((1 - full_bytes / source_bytes) * 100, 1),
                  'thumbnail_reduction_percent': round((1 - thumbnail_bytes / source_bytes) * 100, 1)}))
